"""Safely provision or migrate a TartLab device to the managed-modern profile.

The default CLI action is a read-only release inspection.  Device mutation
requires --execute, --confirm-erase, an authenticated source tag, and a durable
workspace outside the repository.  The workspace may contain Wi-Fi settings
and student files; it must be treated as sensitive and retained until the
device has completed a healthy boot.
"""

